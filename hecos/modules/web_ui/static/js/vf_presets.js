window.VFPresets = {
  currentCategory: "base",
  allPresets: window.VF_STATIC_PRESETS,
  loading: false,

  init: function() {
    this.updateCounts();
    this.renderList();
    this.refresh();
  },

  refresh: async function() {
    if (this.loading) return;
    this.loading = true;
    try {
      if (window.VFApi && window.VFApi.getPresets) {
        const res = await window.VFApi.getPresets();
        if (res && res.ok && res.presets) {
          this.allPresets = {
            base: (res.presets.base && res.presets.base.length > 0) ? res.presets.base : window.VF_STATIC_PRESETS.base,
            cinematic: (res.presets.cinematic && res.presets.cinematic.length > 0) ? res.presets.cinematic : window.VF_STATIC_PRESETS.cinematic,
            custom: res.presets.custom || []
          };
          this.updateCounts();
          this.renderList();
        }
      }
    } catch (e) {
      console.warn("[VoiceForge] API load presets notice (using bundled fallback):", e);
    } finally {
      this.loading = false;
    }
  },

  updateCounts: function() {
    const baseCount = (this.allPresets.base || []).length;
    const cineCount = (this.allPresets.cinematic || []).length;
    const custCount = (this.allPresets.custom || []).length;

    const bTab = document.querySelector('.vf-preset-tab[data-cat="base"]');
    const cTab = document.querySelector('.vf-preset-tab[data-cat="cinematic"]');
    const uTab = document.querySelector('.vf-preset-tab[data-cat="custom"]');

    if (bTab) bTab.textContent = "Base Presets (" + baseCount + ")";
    if (cTab) cTab.textContent = "Cinematic Characters (" + cineCount + ")";
    if (uTab) uTab.textContent = "My Custom Profiles (" + custCount + ")";
  },

  openModal: function() {
    let modal = document.getElementById("vf-preset-modal");
    if (!modal) {
      console.error("[VoiceForge] #vf-preset-modal not found in DOM");
      return;
    }
    // Relocate modal directly under body if nested inside panel-container to guarantee overlay behavior
    if (modal.parentElement !== document.body) {
      document.body.appendChild(modal);
    }
    modal.classList.add("active");
    modal.style.display = "flex";
    modal.style.opacity = "1";
    modal.style.pointerEvents = "auto";
    modal.style.zIndex = "999999";

    this.updateCounts();
    this.renderList();
    this.refresh();
  },

  closeModal: function() {
    const modal = document.getElementById("vf-preset-modal");
    if (modal) {
      modal.classList.remove("active");
      modal.style.display = "none";
      modal.style.opacity = "0";
      modal.style.pointerEvents = "none";
    }
  },

  setCategory: function(cat) {
    this.currentCategory = cat;
    document.querySelectorAll(".vf-preset-tab").forEach(tab => {
      tab.classList.toggle("active", tab.dataset.cat === cat);
    });
    this.renderList();
  },

  renderList: function() {
    const listEl = document.getElementById("vf-preset-list");
    if (!listEl) return;

    const items = (this.allPresets && this.allPresets[this.currentCategory]) ? this.allPresets[this.currentCategory] : [];
    if (!items.length) {
      if (this.currentCategory === "custom") {
        listEl.innerHTML = '<div style="grid-column: 1/-1; text-align:center; padding:35px; color:#64748b;">' +
          '<i class="fas fa-folder-open" style="font-size:2rem; margin-bottom:10px; display:block; opacity:0.5;"></i>' +
          'Nessun timbro personalizzato salvato ancora.<br>' +
          '<span style="font-size:0.8rem; color:#94a3b8;">Modifica i controlli del mixer e fai click su <strong>Bake to Fish Speech</strong> per registrare un nuovo timbro.</span>' +
        '</div>';
      } else {
        listEl.innerHTML = '<div style="grid-column: 1/-1; text-align:center; padding:30px; color:#64748b;">Nessun preset trovato in questa categoria.</div>';
      }
      return;
    }

    listEl.innerHTML = items.map(p => {
      const pName = p.name || p.id;
      const pDesc = p.description || "Profilo timbro vocale";
      const pLang = (p.language || "it").toUpperCase();
      const tags = (p.tags || []).slice(0, 3).map(t => '<span style="font-size:0.65rem; background:rgba(139,92,246,0.2); border:1px solid rgba(139,92,246,0.3); padding:1px 6px; border-radius:4px; color:#c4b5fd;">' + t + '</span>').join("");
      return '<div class="vf-preset-item" style="cursor:pointer; padding:12px; border-radius:10px; background:rgba(255,255,255,0.03); border:1px solid rgba(255,255,255,0.08); transition:all 0.2s;" ' +
             'onclick="window.VFPresets.selectPreset(\'' + p.id + '\')" ' +
             'onmouseenter="this.style.borderColor=\'var(--vf-accent, #00e5ff)\'; this.style.background=\'rgba(0,229,255,0.06)\';" ' +
             'onmouseleave="this.style.borderColor=\'rgba(255,255,255,0.08)\'; this.style.background=\'rgba(255,255,255,0.03)\';">' +
        '<div class="vf-preset-name" style="font-weight:700; color:#fff; font-size:0.92rem;">' + pName + '</div>' +
        '<div class="vf-preset-desc" style="font-size:0.78rem; color:#94a3b8; margin-top:4px; line-height:1.3;">' + pDesc + '</div>' +
        '<div style="display:flex; gap:6px; margin-top:8px; flex-wrap:wrap; align-items:center;">' +
          '<span style="font-size:0.65rem; background:rgba(255,255,255,0.08); padding:2px 7px; border-radius:4px; color:#cbd5e1; font-weight:600;">' + pLang + '</span>' +
          tags +
        '</div>' +
      '</div>';
    }).join("");
  },

  selectPreset: async function(presetId) {
    this.closeModal();
    const items = [...(this.allPresets.base || []), ...(this.allPresets.cinematic || []), ...(this.allPresets.custom || [])];
    const match = items.find(x => x.id === presetId);
    if (match) {
      const titleEl = document.getElementById("vf-current-preset-name");
      if (titleEl) titleEl.textContent = match.name;
    }
    if (window.VFMixer && window.VFMixer.loadPreset) {
      await window.VFMixer.loadPreset(presetId);
    }
  }
};

// Global fallback shortcuts
window.vfOpenPresets = function() {
  if (window.VFPresets && window.VFPresets.openModal) {
    window.VFPresets.openModal();
  } else {
    const modal = document.getElementById("vf-preset-modal");
    if (modal) {
      if (modal.parentElement !== document.body) document.body.appendChild(modal);
      modal.classList.add("active");
      modal.style.display = "flex";
      modal.style.opacity = "1";
      modal.style.pointerEvents = "auto";
      modal.style.zIndex = "999999";
    }
  }
};
